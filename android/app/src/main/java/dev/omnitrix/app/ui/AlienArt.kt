package dev.omnitrix.app.ui

import android.content.res.AssetManager
import android.graphics.BitmapFactory
import android.util.LruCache
import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect
import androidx.compose.runtime.mutableIntStateOf
import androidx.compose.runtime.remember
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.platform.LocalContext
import dev.omnitrix.app.Aliens
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch

/**
 * Alien artwork from assets/aliens/ (generated by tools/build_alien_art.py).
 *
 * Icons for the carousel are small and all load up front. Hologram + glow images load on
 * demand into a small LRU cache off the main thread; [version] bumps when something arrives
 * so a Canvas that reads it redraws. Missing files (clean checkout) simply return null.
 */
class AlienArt(private val assets: AssetManager) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val icons = arrayOfNulls<ImageBitmap>(Aliens.size)
    private val holos = LruCache<Int, Pair<ImageBitmap?, ImageBitmap?>>(10)
    private val pending = HashSet<Int>()
    private val fulls = LruCache<Int, ImageBitmap>(3)

    /** Read inside draw lambdas to redraw when art arrives. */
    val version = mutableIntStateOf(0)

    init {
        scope.launch {
            Aliens.all.forEachIndexed { i, alien -> icons[i] = decode("aliens/icon/${alien.slug}.png") }
            bump()
        }
    }

    fun icon(index: Int): ImageBitmap? = icons[index]
    fun holo(index: Int): ImageBitmap? = holos.get(index)?.first
    fun glow(index: Int): ImageBitmap? = holos.get(index)?.second

    /** Loads [index] and its neighbours so spinning never waits on a decode. */
    fun prefetch(index: Int, radius: Int = 2) {
        for (d in -radius..radius) {
            val i = Math.floorMod(index + d, Aliens.size)
            synchronized(pending) {
                if (holos.get(i) != null || !pending.add(i)) return@synchronized
                scope.launch {
                    val slug = Aliens.all[i].slug
                    holos.put(i, decode("aliens/holo/$slug.png") to decode("aliens/glow/$slug.png"))
                    synchronized(pending) { pending.remove(i) }
                    bump()
                }
            }
        }
    }

    /** Full-colour art for the transformation reveal (loaded only when transforming). */
    fun full(index: Int): ImageBitmap? = fulls.get(index)

    fun requestFull(index: Int) {
        if (fulls.get(index) != null) return
        scope.launch {
            decode("aliens/full/${Aliens.all[index].slug}.png")?.let { fulls.put(index, it) }
            bump()
        }
    }

    fun close() = scope.cancel()

    private fun bump() = scope.launch(Dispatchers.Main) { version.intValue++ }

    private fun decode(path: String): ImageBitmap? = try {
        assets.open(path).use { BitmapFactory.decodeStream(it) }?.asImageBitmap()?.also { it.prepareToDraw() }
    } catch (_: java.io.IOException) {
        null
    }
}

@Composable
fun rememberAlienArt(): AlienArt {
    val assets = LocalContext.current.assets
    val art = remember { AlienArt(assets) }
    DisposableEffect(art) { onDispose { art.close() } }
    return art
}
